/**
 * Profile photos, personal theme choice and organisation branding.
 *
 *   P1  a photo is re-encoded with nothing hidden left (no EXIF, no GPS),
 *       stored at every size, served only to signed-in people, replaced
 *       cleanly by a new version, and deleted completely
 *   P2  awkward files: a rotated photo, a tiny one, one near 10 MB, one over,
 *       an iPhone HEIC and something that is not a picture
 *   P3  an administrator removes a photo only with a reason; the person is
 *       told and it is in the audit trail; nobody else can
 *   P4  a photo suggested by an administrator is used only when the person
 *       accepts it; declining deletes it
 *   T1  light, dark or match my device, and an accent, follow the person to a
 *       new sign-in
 *   B1  branding is public to read; only settings.manage changes it; colours
 *       that fail are refused with a passing suggestion; save, undo and reset;
 *       the installed app's manifest follows
 *   B2  logos: an SVG with anything that could run is refused; a clean one is
 *       served with a strict policy and icons are made from it
 *
 * Every picture here is generated by the test (shapes and noise, with made-up
 * camera data); no real photo is used.
 */
