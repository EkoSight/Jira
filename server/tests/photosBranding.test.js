const call = async (method, p, { token, body, form } = {}) => {
  const res = await fetch(`${baseUrl}${p.startsWith('/manifest') ? '' : '/api/taskflow'}${p}`, {
    method,
    headers: { ...(form ? {} : { 'content-type': 'application/json' }), ...(token ? { authorization: `Bearer ${token}` } : {}) },
    body: form || (body === undefined ? undefined : JSON.stringify(body)),
  });
  const type = res.headers.get('content-type') || '';
  const buf = Buffer.from(await res.arrayBuffer());
  let parsed = buf;
  if (/json/.test(type)) parsed = JSON.parse(buf.toString('utf8') || 'null');
  return { status: res.status, body: parsed, headers: res.headers };
};
const ok = (res, status = 200) => { assert.equal(res.status, status, Buffer.isBuffer(res.body) ? `${res.status}` : JSON.stringify(res.body)); return res.body; };
const skip = (t) => { if (!available) { t.skip('no database'); return true; } return false; };
const form = (files, fields = {}) => {
  const f = new FormData();
  for (const [name, [buf, type, filename]] of Object.entries(files)) f.append(name, new Blob([buf], { type }), filename);
  for (const [k, v] of Object.entries(fields)) f.append(k, typeof v === 'string' ? v : JSON.stringify(v));
  return f;
};

// a made-up "camera photo": shapes, with camera details and a GPS position in its EXIF
async function cameraJpeg({ width = 900, height = 1200, orientation } = {}) {
  const svg = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><rect width="100%" height="100%" fill="#7a9a5a"/><circle cx="${width / 2}" cy="${height / 3}" r="${Math.min(width, height) / 5}" fill="#c9a27e"/><rect x="${width / 4}" y="${height / 2}" width="${width / 2}" height="${height / 2}" fill="#2d3e50"/></svg>`);
  let img = sharp(svg).jpeg({ quality: 90 }).withExif({
    IFD0: { Make: 'MadeUpCam', Model: 'Sample 1', Software: 'test' },
    IFD3: { GPSLatitudeRef: 'N', GPSLatitude: '28/1 36/1 50/1', GPSLongitudeRef: 'E', GPSLongitude: '77/1 12/1 30/1' },
  });
  if (orientation) img = img.withMetadata({ orientation });
  return img.toBuffer();
}

