test('P1: a photo is stored clean at every size, shown only to signed-in people, replaced and deleted completely', async (t) => {
  if (skip(t)) return;
  const camera = await cameraJpeg();
  const inMeta = await sharp(camera).metadata();
  assert.ok(inMeta.exif && inMeta.exif.includes(Buffer.from('MadeUpCam')), 'the test photo really carries camera data');
  assert.ok(inMeta.exif.length > 100);

  const saved = ok(await call('POST', '/photos/me', {
    token: tokens.isha,
    form: form({ photo: [camera, 'image/jpeg', 'me.jpg'], original: [camera, 'image/jpeg', 'me.jpg'] }, { edit: { crop: { x: 0.5, y: 0.4, size: 0.6 }, angle: 2, fixes: { light: true, colour: true, sharpen: true, background: false }, face: true } }),
  }), 201);
  assert.equal(saved.version, 1);
  const dir = path.join(personDir(ids.isha), 'v1');
  assert.deepEqual(listFiles(dir).sort(), ['128.webp', '256.webp', '512.webp', '64.webp', 'original.webp']);
  for (const name of listFiles(dir)) {
    const file = fs.readFileSync(path.join(dir, name));
    const meta = await sharp(file).metadata();
    assert.equal(meta.format, 'webp');
    assert.equal(meta.exif, undefined, `${name} has no EXIF`);
    assert.equal(meta.xmp, undefined, `${name} has no XMP`);
    assert.ok(!file.includes(Buffer.from('MadeUpCam')), `${name} carries no camera name`);
    assert.ok(!file.includes(Buffer.from('Exif')), `${name} has no EXIF block`);
    if (name !== 'original.webp') assert.equal(meta.width, Number(name.split('.')[0]));
  }

  // anyone signed in sees it; nobody else; old versions are not served
  const versions = ok(await call('GET', '/photos/versions', { token: tokens.ravi })).versions;
  assert.deepEqual(versions, [{ id: ids.isha, v: 1 }]);
  const pic = await call('GET', `/photos/${ids.isha}/128?v=1`, { token: tokens.ravi });
  assert.equal(pic.status, 200);
  assert.equal(pic.headers.get('content-type'), 'image/webp');
  assert.match(pic.headers.get('cache-control'), /private/);
  assert.match(pic.headers.get('cache-control'), /immutable/);
  assert.equal((await call('GET', `/photos/${ids.isha}/128?v=1`)).status, 401);
  assert.equal((await call('GET', `/photos/${ids.isha}/100?v=1`, { token: tokens.ravi })).status, 404, 'only the stored sizes');
  ok(await call('GET', '/photos/me/original', { token: tokens.isha }));
  assert.match((await call('GET', '/photos/me/original', { token: tokens.isha })).headers.get('cache-control'), /no-store/);
  const mine = ok(await call('GET', '/photos/me', { token: tokens.isha }));
  assert.equal(mine.photo.edit.crop.size, 0.6, 'the editor can be re-opened on the original');
  assert.ok(mine.photo.consent_at);
  assert.equal(ok(await call('GET', '/auth/me', { token: tokens.isha })).user.photo_version, 1);

  // a new photo replaces the old one, whose files are gone
  ok(await call('POST', '/photos/me', { token: tokens.isha, form: form({ photo: [await cameraJpeg({ width: 600, height: 600 }), 'image/jpeg', 'b.jpg'] }) }), 201);
  assert.ok(!fs.existsSync(dir), 'version 1 removed');
  assert.equal((await call('GET', `/photos/${ids.isha}/128?v=1`, { token: tokens.ravi })).status, 404);
  ok(await call('GET', `/photos/${ids.isha}/128?v=2`, { token: tokens.ravi }));
  assert.equal((await call('GET', '/photos/me/original', { token: tokens.isha })).status, 404, 'no original was sent this time');

  // deleting removes every size and the folder
  ok(await call('DELETE', '/photos/me', { token: tokens.isha }));
  assert.ok(!fs.existsSync(personDir(ids.isha)));
  assert.equal((await call('GET', `/photos/${ids.isha}/64?v=2`, { token: tokens.ravi })).status, 404);
  assert.equal(ok(await call('GET', '/auth/me', { token: tokens.isha })).user.photo_version, null);
  const trail = (await query(`SELECT action FROM attendance_audit WHERE entity_type = 'USER_PHOTO' AND subject_user_id = $1 ORDER BY id`, [ids.isha])).rows.map((r) => r.action);
  assert.deepEqual(trail, ['UPLOADED', 'UPLOADED', 'DELETED']);
});

