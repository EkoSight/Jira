test('P2: rotated, tiny, near-limit and over-limit photos, HEIC and non-pictures are each handled', async (t) => {
  if (skip(t)) return;
  // turned on its side by the camera: stored upright
  const sideways = await cameraJpeg({ width: 400, height: 300, orientation: 6 });
  ok(await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [sideways, 'image/jpeg', 's.jpg'], original: [sideways, 'image/jpeg', 's.jpg'] }) }), 201);
  const original = await sharp(fs.readFileSync(path.join(personDir(ids.ravi), 'v1', 'original.webp'))).metadata();
  assert.deepEqual([original.width, original.height, original.orientation], [300, 400, undefined]);

  // too small to use
  const tiny = await sharp({ create: { width: 20, height: 20, channels: 3, background: '#888888' } }).png().toBuffer();
  const tooSmall = await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [tiny, 'image/png', 't.png'] }) });
  assert.equal(tooSmall.status, 400);
  assert.equal(tooSmall.body.details.code, 'TOO_SMALL');
  // small but usable: made up to every size
  const small = await sharp({ create: { width: 48, height: 48, channels: 3, background: '#888888' } }).png().toBuffer();
  ok(await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [small, 'image/png', 'small.png'] }) }), 201);

  // just under 10 MB: accepted; over: refused before it is read
  const noise = (side) => sharp(crypto.randomBytes(side * side * 3), { raw: { width: side, height: side, channels: 3 } }).png({ compressionLevel: 0 }).toBuffer();
  const big = await noise(1820);
  assert.ok(big.length > 9 * 1024 * 1024 && big.length < 10 * 1024 * 1024, `${big.length}`);
  ok(await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [big, 'image/png', 'big.png'] }) }), 201);
  const huge = await noise(1900);
  const over = await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [huge, 'image/png', 'huge.png'] }) });
  assert.equal(over.status, 400);
  assert.match(over.body.error, /10 MB/);

  // an iPhone HEIC: a clear explanation, not a failure
  const heic = Buffer.concat([Buffer.from([0, 0, 0, 0x18]), Buffer.from('ftypheic'), Buffer.alloc(64)]);
  const h = await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [heic, 'image/heic', 'IMG_0001.HEIC'] }) });
  assert.equal(h.status, 400);
  assert.equal(h.body.details.code, 'HEIC');
  assert.match(h.body.error, /JPEG/);
  const notPicture = await call('POST', '/photos/me', { token: tokens.ravi, form: form({ photo: [Buffer.from('hello'), 'image/jpeg', 'x.jpg'] }) });
  assert.equal(notPicture.status, 400);
  assert.equal(ok(await call('GET', '/auth/me', { token: tokens.ravi })).user.photo_version, 3, 'refused uploads changed nothing');
});

