test('P4: a suggested photo is used only when the person accepts it; declining deletes it', async (t) => {
  if (skip(t)) return;
  const pic = await cameraJpeg({ width: 700, height: 700 });
  ok(await call('POST', `/photos/${ids.meera}/suggest`, { token: tokens.isha, form: form({ photo: [pic, 'image/jpeg', 'x.jpg'] }) }), 403);
  const s = ok(await call('POST', `/photos/${ids.meera}/suggest`, { token: tokens.admin, form: form({ photo: [pic, 'image/jpeg', 'x.jpg'] }, { note: 'From the team day' }) }), 201);
  assert.equal(ok(await call('GET', '/auth/me', { token: tokens.meera })).user.photo_version, null, 'not used yet');
  assert.ok((await query(`SELECT 1 FROM notifications WHERE user_id = $1 AND type = 'photo_suggested'`, [ids.meera])).rows.length);
  const mine = ok(await call('GET', '/photos/me', { token: tokens.meera }));
  assert.equal(mine.proposals[0].id, s.id);
  ok(await call('GET', `/photos/suggestions/${s.id}/picture`, { token: tokens.meera }));
  assert.equal((await call('GET', `/photos/suggestions/${s.id}/picture`, { token: tokens.isha })).status, 404, 'nobody else sees it');
  ok(await call('POST', `/photos/me/suggestions/${s.id}/accept`, { token: tokens.isha }), 404);
  ok(await call('POST', `/photos/me/suggestions/${s.id}/accept`, { token: tokens.meera }));
  const row = (await query('SELECT uploaded_by, consent_at, status FROM user_photos WHERE user_id = $1', [ids.meera])).rows[0];
  assert.deepEqual([row.uploaded_by, row.status], [ids.admin, 'ACTIVE']);
  assert.ok(row.consent_at, 'agreement recorded when accepted');
  assert.equal(ok(await call('GET', '/auth/me', { token: tokens.meera })).user.photo_version, 1);
  ok(await call('POST', `/photos/me/suggestions/${s.id}/accept`, { token: tokens.meera }), 409);

  const s2 = ok(await call('POST', `/photos/${ids.ravi}/suggest`, { token: tokens.admin, form: form({ photo: [pic, 'image/jpeg', 'x.jpg'] }) }), 201);
  ok(await call('POST', `/photos/me/suggestions/${s2.id}/decline`, { token: tokens.ravi }));
  assert.ok(!fs.existsSync(path.join(UPLOADS, 'photos', 'proposals', String(s2.id))), 'declined files deleted');
  assert.equal(ok(await call('GET', '/auth/me', { token: tokens.ravi })).user.photo_version, 3, 'their own photo is untouched');
  ok(await call('POST', `/photos/${ids.admin}/suggest`, { token: tokens.admin, form: form({ photo: [pic, 'image/jpeg', 'x.jpg'] }) }), 400);
});

